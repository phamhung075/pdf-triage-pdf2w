// ---- JS string semantics helpers ----

// jsReplaceFirst ports `str.replace(search, replacement)` for a string `search`: the first
// occurrence only, with GetSubstitution expansion of the replacement.
func jsReplaceFirst(s, search, replacement string) string {
	i := strings.Index(s, search)
	if i < 0 {
		return s
	}
	return s[:i] + expandJSReplacement(s, replacement, i, search) + s[i+len(search):]
}

// jsReplaceAll ports a global `str.replace(/literal/g, replacement)`: every non-overlapping
// occurrence, with GetSubstitution expansion computed against the original input.
func jsReplaceAll(s, search, replacement string) string {
	if search == "" {
		return s
	}
	var b strings.Builder
	pos := 0
	for {
		i := strings.Index(s[pos:], search)
		if i < 0 {
			break
		}
		start := pos + i
		b.WriteString(s[pos:start])
		b.WriteString(expandJSReplacement(s, replacement, start, search))
		pos = start + len(search)
	}
	b.WriteString(s[pos:])
	return b.String()
}

// expandJSReplacement ports the GetSubstitution replacement patterns that apply to a string
// search (no capture groups): `$$`, `$&`, the before-match dollar-backtick form and `$'`. Any
// other `$x` is left literal, as JS does when the pattern names no capture group.
func expandJSReplacement(s, replacement string, matchStart int, matched string) string {
	var b strings.Builder
	for i := 0; i < len(replacement); i++ {
		c := replacement[i]
		if c != '$' || i+1 >= len(replacement) {
			b.WriteByte(c)
			continue
		}
		switch replacement[i+1] {
		case '$':
			b.WriteByte('$')
			i++
		case '&':
			b.WriteString(matched)
			i++
		case '`':
			b.WriteString(s[:matchStart])
			i++
		case '\'':
			b.WriteString(s[matchStart+len(matched):])
			i++
		default:
			b.WriteByte('$')
		}
	}
	return b.String()
}

// jsTrim is `String.prototype.trim()`: it strips exactly the JavaScript whitespace set. Go's
// strings.TrimSpace would additionally strip U+0085 NEL and would leave U+FEFF.
func jsTrim(s string) string {
	return strings.TrimFunc(s, isJSWhitespace)
}

// isJSWhitespace reports whether r is in JavaScript's WhiteSpace+LineTerminator set.
func isJSWhitespace(r rune) bool {
	switch r {
	case '\t', '\n', '\v', '\f', '\r', ' ',
		0x00A0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000, 0xFEFF:
		return true
	}
	return r >= 0x2000 && r <= 0x200A
}

// utf16Len is JavaScript's `str.length`: the number of UTF-16 code units, not runes.
func utf16Len(s string) int {
	n := 0
	for _, r := range s {
		if r > 0xFFFF {
			n += 2
		} else {
			n++
		}
	}
	return n
}

// utf16Slice reproduces `str.substring(0, n)`: the first n UTF-16 code units. A rune whose code
// units would straddle the cut is dropped; JS would keep a lone surrogate there, which a Go UTF-8
// string cannot represent.
func utf16Slice(s string, n int) string {
	if n <= 0 {
		return ""
	}
	units := 0
	for i, r := range s {
		w := 1
		if r > 0xFFFF {
			w = 2
		}
		if units+w > n {
			return s[:i]
		}
		units += w
	}
	return s
}
